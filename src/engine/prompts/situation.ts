/**
  * 评分的历史。
 *
 * 把导演自己前几轮打的分回放给它看 —— 它自己就会发现"我磨了三轮"，
 * 这比外面塞一条"你必须做到什么"的命令管用：命令可以抗，自己写下的账没法赖。
 */
function scoreHistory(scores: number[], streak: number): string {
  if (!scores.length) return '（这是第一轮，还没有历史评分）'
  const recent = scores.slice(-4)
  const trend = recent.join(' → ')
  const stuck = recent.length >= 3 && recent[recent.length - 1] - recent[0] <= 10
  return (
    `最近几轮你自己打的分：${trend}\n` +
    `（现在要打的是第 ${streak} 轮）\n` +
    (stuck ? '\n**看出来了吗 —— 连着几轮几乎没动。那不是在慢热，那是在磨。**' : '')
  )
}

